function roleLevel(role: string) {
  if (role === 'admin') return 3
  if (role === 'supervisor') return 2
  return 1
}

interface SidebarProps {
  profile: Profile
}

export default function Sidebar({ profile }: SidebarProps) {
  const pathname = usePathname()
  const supabase = createClient()

  const handleSignOut = async () => {
    await supabase.auth.signOut()
    window.location.href = '/login'
  }

  const initials =
    `${profile.first_name?.[0] ?? ''}${profile.last_name?.[0] ?? ''}`.toUpperCase()

  const userRoleLevel = roleLevel(profile.role)

  const isActive = (href: string) => {
    if (href === '/dashboard') return pathname === '/dashboard'
    return pathname.startsWith(href)
  }

  return (
    <aside className="w-64 bg-navy-900 flex flex-col h-screen shrink-0 overflow-hidden">
      {/* Logo */}
      <div className="flex items-center gap-3 px-5 py-5 border-b border-navy-800">
        <div className="w-9 h-9 bg-white rounded-lg flex items-center justify-center shrink-0">
          <span className="text-sm font-black text-navy-900">GCS</span>
        </div>
        <div>
          <p className="text-white text-sm font-bold leading-tight">GCS</p>
          <p className="text-navy-300 text-xs">PD Platform</p>
        </div>
      </div>

      {/* Nav */}
      <nav className="flex-1 overflow-y-auto px-3 py-4 space-y-6">
        {navSections.map((section) => {
          const minLevel = section.minRole ? roleLevel(section.minRole) : 1
          if (userRoleLevel < minLevel) return null

          const visibleItems = section.items.filter(
            (item) => userRoleLevel >= (item.minRole ? roleLevel(item.minRole) : 1)
          )
          if (visibleItems.length === 0) return null

          return (
            <div key={section.label}>
              <p className="text-navy-400 text-[10px] font-semibold uppercase tracking-widest px-3 mb-2">
                {section.label}
              </p>
              <ul className="space-y-0.5">
                {visibleItems.map((item) => (
                  <li key={item.href}>
                    <Link
                      href={item.href}
                      className={clsx(
                        'flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors',
                        isActive(item.href)
                          ? 'bg-white/15 text-white'
                          : 'text-navy-200 hover:bg-white/10 hover:text-white'
                      )}
                    >
                      <span className={clsx(isActive(item.href) ? 'text-white' : 'text-navy-300')}>
                        {item.icon}
                      </span>
                      {item.label}
                    </Link>
                  </li>
                ))}
              </ul>
            </div>
          )
        })}
      </nav>

      {/* User footer */}
      <div className="border-t border-navy-800 p-4">
        <div className="flex items-center gap-3 mb-3">
          {profile.avatar_url ? (
            <img
              src={profile.avatar_url}
              alt={`${profile.first_name} ${profile.last_name}`}
              className="w-9 h-9 rounded-full object-cover shrink-0"
            />
          ) : (
            <div className="w-9 h-9 rounded-full bg-navy-600 flex items-center justify-center shrink-0">
              <span className="text-white text-sm font-semibold">{initials}</span>
            </div>
          )}
          <div className="min-w-0">
            <p className="text-white text-sm font-medium truncate">
              {profile.first_name} {profile.last_name}
            </p>
            <p className="text-navy-400 text-xs capitalize">{profile.role}</p>
          </div>
        </div>
        <button
          onClick={handleSignOut}
          className="w-full flex items-center gap-2 px-3 py-2 text-navy-300 hover:text-white hover:bg-white/10 rounded-lg text-sm transition-colors"
        >
          <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15M12 9l-3 3m0 0l3 3m-3-3h12.75" />
          </svg>
          Sign out
        </button>
      </div>
    </aside>
  )
}
