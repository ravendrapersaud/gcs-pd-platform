-- ── Backfill resource audience / themes / subjects / covers ──────────
-- The Google Doc import (import_resources_from_doc.sql) only wrote the
-- category into `tags`, but the resource cards and filters read the
-- audience/themes/subjects columns - so every imported resource showed
-- "-" and matched no filter. This backfills all three, leading each
-- resource's themes with its doc category (now an active theme term,
-- see migration_doc_theme_terms.sql), plus cover_image where a real
-- image could be verified (og:image, Drive thumbnail, or Open Library
-- cover by ISBN). Rows whose covers could not be verified keep
-- cover_image null and fall back to the card's type gradient.
--
-- Backfill only: a column already holding values is left alone, so
-- later admin edits in the UI survive a re-run. Safe to run repeatedly.

